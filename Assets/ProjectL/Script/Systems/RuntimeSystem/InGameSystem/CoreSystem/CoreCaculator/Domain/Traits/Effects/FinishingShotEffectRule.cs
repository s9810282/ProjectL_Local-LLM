namespace ProjectL.Systems.RuntimeSystem.InGameSystem.CoreSystem.CoreCaculator.Domain.Traits.Effects
{
    internal sealed class FinishingShotEffectRule : IEffectOrderedHitRule
    {
        public bool RequiresOrderedHits => true;

        private readonly FinishingShotTraitDefinition _definition;
        private readonly FinishingShotTraitRule _rule;
        internal FinishingShotEffectRule(FinishingShotTraitDefinition definition, FinishingShotTraitRule rule)
        {
            _definition = definition ?? throw new ArgumentNullException(nameof(definition));
            _rule = rule ?? throw new ArgumentNullException(nameof(rule));
        }
        internal bool Qualifies(in EffectRuleInput input, int attack, HealthStateSnapshot health)
        {
            Validate(input);
            return _rule.Qualifies(attack, health, _definition.AttackThresholdPercent);
        }
        private void Validate(in EffectRuleInput input)
        {
            if (input.State is not StatelessEffectStateSnapshot ||
                TraitEffectOrigin.GetRequiredTraitKey(input.Origin, new EntityId(input.Origin.OwnerInstanceId)) != _definition.TraitKey)
                throw new ArgumentException("특성 출처와 상태가 일치해야 합니다.", nameof(input));
        }
    }
}
